"""
Compare two homr token strings: a ground truth and one generated by homr.

Usage:
    poetry run python validation/compare_tokens.py <ground_truth> <generated> [options]

Each argument is either a path to a token file (e.g. a .tokens file from a
dataset) or a literal token string. Existing paths are read as files,
everything else is treated as a literal string. Both 6-field symbols
(`rhythm pitch lift articulation slur position`) and legacy 5-field or
4-field symbols are supported, chord members may be joined with '&'.
Control symbols (BOS, EOS, PAD) are ignored.

The comparison follows the methodology of the Transcription Smoke Test
(validation/symbol_error_rate_torch.py): both sequences are grouped into
chords via sort_token_chords and flattened, so that chord members are
compared order-independently. Then it reports:

  - Symbol error rate (SER): Levenshtein distance between the two
    symbol sequences, normalized by the ground truth length
  - Match/substitute/delete/insert counts
  - Which token branches (rhythm, pitch, lift, articulation, slur,
    position) differ for substituted symbols
  - An aligned, side-by-side diff of every symbol

Options:
  --ignore-articulation  Drop articulations before comparing (same as the
                         SER script does, useful to compare against older
                         models which had no articulations)
  --ignore-position      Drop the upper/lower staff position before comparing
  --only PREFIXES        Only compare symbols whose rhythm starts with one of
                         these comma separated prefixes, e.g. note,rest
  --diff-only            Only print mismatching regions of the diff
  --context N            Lines of context around mismatches with --diff-only

Exit code is 0 when both strings are identical, 1 when they differ and
2 when an input could not be parsed.
"""

# ruff: noqa: S101, T201

import argparse
import difflib
import os
import sys

import editdistance

from homr.simple_logging import eprint
from homr.transformer.vocabulary import EncodedSymbol, sort_token_chords
from training.transformer.training_vocabulary import read_token_lines

_CONTROL_TOKENS = ("BOS", "EOS", "PAD")
_FIELD_NAMES = ("rhythm", "pitch", "lift", "articulation", "slur", "position")
_COL = 66

SymbolKey = tuple[str, str, str, str, str, str]


def _split_flattened_line(line: str) -> list[str]:
    """
    A line containing far more fields than a single symbol is likely a token
    string in which the newlines got lost. Split it into one line per symbol,
    assuming 6-field symbols (or 5-field ones for legacy data). Chord members
    (joined with '&') are kept together on one line, so that chords are
    grouped and sorted exactly like in a multi-line token string.
    """
    fields = line.split()
    while fields and fields[0] in _CONTROL_TOKENS:
        fields = fields[1:]
    while fields and fields[-1] in _CONTROL_TOKENS:
        fields = fields[:-1]
    # Well formed lines have at most a handful of fields, one per symbol plus
    # one per '&'. Lines with dozens of fields must be flattened strings.
    is_flattened = len(fields) > 60 or (len(fields) > 6 and "&" not in line)
    if not is_flattened:
        return [" ".join(fields)] if fields else []

    # '&'-joined chord members fuse the last field of one symbol with the
    # first field of the next one, e.g. 'upper&note_4'. Split them apart
    # while remembering which symbol continues a chord.
    unglued: list[tuple[str, bool]] = []
    for field in fields:
        for i, part in enumerate(field.split("&")):
            unglued.append((part, i > 0))

    for width in (6, 5):
        if len(unglued) > width and len(unglued) % width == 0:
            lines: list[str] = []
            continues_chord = False
            for i in range(0, len(unglued), width):
                symbol = " ".join(text for text, _ in unglued[i : i + width])
                if continues_chord and lines:
                    lines[-1] += "&" + symbol
                else:
                    lines.append(symbol)
                next_index = i + width
                continues_chord = (
                    unglued[next_index][1] if next_index < len(unglued) else False
                )
            return lines
    raise ValueError(
        f"Found a flattened token string with {len(unglued)} fields, but that "
        "number is not divisible by 6 or 5, so it cannot be split into symbols"
    )


def _is_control_entry(entry: str) -> bool:
    """
    True for entries like 'BOS', 'EOS' or 'BOS . . . . .' which some
    inference outputs print around the actual tokens.
    """
    fields = entry.split()
    if not fields or fields[0] not in _CONTROL_TOKENS:
        return False
    return all(field in (".", "_") for field in fields[1:])


def _read_token_string(token_string: str) -> list[EncodedSymbol]:
    """
    Parse a token string into a flat sequence of encoded symbols.
    """
    lines = []
    for line in token_string.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        first_entry = stripped.split("&")[0].strip()
        if _is_control_entry(first_entry):
            continue
        lines.extend(_split_flattened_line(stripped))
    try:
        return read_token_lines(lines)
    except ValueError as e:
        raise ValueError(str(e)) from e


def _load_tokens(argument: str) -> list[EncodedSymbol]:
    """
    Load tokens from a file path or from a literal token string.
    """
    if os.path.exists(argument):
        with open(argument, encoding="utf-8") as f:
            token_string = f.read()
        source = "file " + argument
    else:
        token_string = argument
        source = "literal string"
    try:
        return _read_token_string(token_string)
    except ValueError as e:
        raise ValueError(f"Failed to parse {source}: {e}") from e


def _comparison_key(
    symbol: EncodedSymbol,
    ignore_articulation: bool,
    ignore_position: bool,
) -> SymbolKey:
    """
    The six fields of a symbol, with ignored fields blanked out so that
    they no longer contribute to the comparison.
    """
    return (
        symbol.rhythm,
        symbol.pitch,
        symbol.lift,
        "." if ignore_articulation else symbol.articulation,
        symbol.slur,
        "." if ignore_position else symbol.position,
    )


def _flatten_and_filter(
    symbols: list[EncodedSymbol],
    only_prefixes: tuple[str, ...] | None,
) -> list[EncodedSymbol]:
    """
    Group into chords, sort chord members and flatten, so that the
    comparison doesn't depend on the order of chord members.
    """
    flattened = [symbol for chord in sort_token_chords(symbols) for symbol in chord]
    if only_prefixes is not None:
        flattened = [s for s in flattened if s.rhythm.startswith(only_prefixes)]
    return flattened


def _align(
    expected: list[EncodedSymbol],
    actual: list[EncodedSymbol],
    ignore_articulation: bool,
    ignore_position: bool,
) -> list[tuple[str, EncodedSymbol | None, EncodedSymbol | None]]:
    """
    Align both sequences with the same difflib approach as ned_score.py.
    Returns a list of (event_type, expected_symbol, actual_symbol) events,
    where event_type is one of match, substitute, delete, insert and only
    one of the two symbols is set for delete/insert.
    """
    expected_keys = [_comparison_key(s, ignore_articulation, ignore_position) for s in expected]
    actual_keys = [_comparison_key(s, ignore_articulation, ignore_position) for s in actual]
    matcher = difflib.SequenceMatcher(None, expected_keys, actual_keys, autojunk=False)
    events: list[tuple[str, EncodedSymbol | None, EncodedSymbol | None]] = []
    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        if tag == "equal":
            for k in range(i2 - i1):
                events.append(("match", expected[i1 + k], actual[j1 + k]))
        elif tag == "delete":
            for k in range(i2 - i1):
                events.append(("delete", expected[i1 + k], None))
        elif tag == "insert":
            for k in range(j2 - j1):
                events.append(("insert", None, actual[j1 + k]))
        elif tag == "replace":
            n_sub = min(i2 - i1, j2 - j1)
            for k in range(n_sub):
                events.append(("substitute", expected[i1 + k], actual[j1 + k]))
            for k in range(n_sub, i2 - i1):
                events.append(("delete", expected[i1 + k], None))
            for k in range(n_sub, j2 - j1):
                events.append(("insert", None, actual[j1 + k]))
    return events


def _fmt(symbol: EncodedSymbol) -> str:
    return (
        f"{symbol.rhythm:24s} {symbol.pitch:6s} {symbol.lift:4s}"
        f" {symbol.articulation:12s} {symbol.slur:8s} {symbol.position}"
    )


def _print_event(event: tuple[str, EncodedSymbol | None, EncodedSymbol | None]) -> None:
    event_type, exp, act = event
    if event_type == "match":
        assert exp is not None and act is not None
        print(f"  {_fmt(exp):<{_COL}}  {_fmt(act)}")
    elif event_type == "substitute":
        assert exp is not None and act is not None
        print(f"! {_fmt(exp):<{_COL}}! {_fmt(act)}")
    elif event_type == "delete":
        assert exp is not None
        print(f"< {_fmt(exp):<{_COL}}")
    elif event_type == "insert":
        assert act is not None
        print(f"  {'':<{_COL}}> {_fmt(act)}")


def _print_diff(
    events: list[tuple[str, EncodedSymbol | None, EncodedSymbol | None]],
    diff_only: bool,
    context: int,
) -> None:
    print(f"{'EXPECTED':^{_COL}}    {'ACTUAL (homr)':^{_COL}}")
    print("=" * ((_COL + 2) * 2))
    if not diff_only:
        for event in events:
            _print_event(event)
        return

    diff_indices = [i for i, event in enumerate(events) if event[0] != "match"]
    shown: set[int] = set()
    for index in diff_indices:
        shown.update(range(max(0, index - context), min(len(events), index + context + 1)))
    previous = None
    for i, event in enumerate(events):
        if i not in shown:
            continue
        if previous is not None and i > previous + 1:
            print("     ...")
        _print_event(event)
        previous = i


def _print_substitution_breakdown(
    events: list[tuple[str, EncodedSymbol | None, EncodedSymbol | None]],
    ignore_articulation: bool,
    ignore_position: bool,
) -> None:
    breakdown = dict.fromkeys(_FIELD_NAMES, 0)
    for event_type, exp, act in events:
        if event_type != "substitute":
            continue
        assert exp is not None and act is not None
        exp_key = _comparison_key(exp, ignore_articulation, ignore_position)
        act_key = _comparison_key(act, ignore_articulation, ignore_position)
        for field, e, a in zip(_FIELD_NAMES, exp_key, act_key, strict=True):
            if e != a:
                breakdown[field] += 1
    if any(breakdown.values()):
        print()
        print("Differing fields in substitutions:")
        for field in _FIELD_NAMES:
            if breakdown[field] > 0:
                print(f"  {field:13s}: {breakdown[field]}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Compare a ground truth token string with one generated by homr."
    )
    parser.add_argument("ground_truth", type=str, help="Token file path or literal token string")
    parser.add_argument("generated", type=str, help="Token file path or literal token string")
    parser.add_argument(
        "--ignore-articulation",
        action="store_true",
        help="Ignore articulations while comparing",
    )
    parser.add_argument(
        "--ignore-position",
        action="store_true",
        help="Ignore the upper/lower staff position while comparing",
    )
    parser.add_argument(
        "--only",
        type=str,
        default=None,
        help="Comma separated rhythm prefixes to compare, e.g. note,rest",
    )
    parser.add_argument(
        "--diff-only",
        action="store_true",
        help="Only print the mismatching regions of the diff",
    )
    parser.add_argument(
        "--context",
        type=int,
        default=2,
        help="Lines of context around mismatches when using --diff-only",
    )
    args = parser.parse_args()

    try:
        expected = _load_tokens(args.ground_truth)
        actual = _load_tokens(args.generated)
    except ValueError as e:
        eprint(e)
        sys.exit(2)

    only_prefixes = tuple(p.strip() for p in args.only.split(",")) if args.only else None
    expected = _flatten_and_filter(expected, only_prefixes)
    actual = _flatten_and_filter(actual, only_prefixes)

    events = _align(expected, actual, args.ignore_articulation, args.ignore_position)

    counts = dict.fromkeys(("match", "substitute", "delete", "insert"), 0)
    for event_type, _, _ in events:
        counts[event_type] += 1

    expected_keys = [
        _comparison_key(s, args.ignore_articulation, args.ignore_position) for s in expected
    ]
    actual_keys = [
        _comparison_key(s, args.ignore_articulation, args.ignore_position) for s in actual
    ]
    distance = editdistance.eval(expected_keys, actual_keys)
    ser = distance / len(expected_keys) if expected_keys else (1.0 if actual_keys else 0.0)

    print(f"Ground truth symbols: {len(expected)}")
    print(f"Generated symbols   : {len(actual)}")
    print()
    print(f"Matches      : {counts['match']}")
    print(f"Substitutions: {counts['substitute']}")
    print(f"Deletions    : {counts['delete']} (missing from homr)")
    print(f"Insertions   : {counts['insert']} (extra in homr)")
    print()
    print(f"SER: {100 * ser:.2f}% (edit distance {distance} / {len(expected_keys)} symbols)")

    _print_substitution_breakdown(events, args.ignore_articulation, args.ignore_position)

    print()
    _print_diff(events, args.diff_only, args.context)

    sys.exit(0 if distance == 0 else 1)


if __name__ == "__main__":
    main()
